// 숫자 읽기 규칙 검증 —  node tools/qt-tts/num_ko.test.mjs
import { sino, native, readNumbers } from './num_ko.mjs';

const cases = [
  // [입력, 기대값]  — 목사님이 지적하신 사례
  ['너비가 50규빗이었다', '너비가 오십 규빗이었다'],
  ['길이가 100규빗', '길이가 백 규빗'],
  ['500명이 모였다', '오백 명이 모였다'],
  // 한자어 수사
  ['20규빗 되는 안뜰', '이십 규빗 되는 안뜰'],
  ['1,000명', '천 명'],
  ['12000원', '만이천 원'],
  ['2026년', '이천이십육 년'],
  ['3층 건물', '삼 층 건물'],
  // 고유어로 세는 단위
  ['세 개 층의 쪽방', '세 개 층의 쪽방'],
  ['3개 층', '세 개 층'],
  ['2명', '두 명'],
  ['20살', '스무 살'],
  ['21살', '스물한 살'],
  ['5시간', '다섯 시간'],
  ['양 12마리', '양 열두 마리'],
  ['100명', '백 명'],              // 100 이상은 한자어
  ['5개월', '오 개월'],             // 개월은 한자어 (개 아님)
  ['50달러', '오십 달러'],          // 달러는 한자어 (달 아님)
  // 날짜·시각·범위·소수·퍼센트
  ['2026-08-19', '이천이십육년 팔월 십구일'],
  ['3시 30분', '세 시 삼십 분'],
  ['10~20', '십에서 이십'],
  ['3.5', '삼 점 오'],
  ['50%', '오십 퍼센트'],
  // 숫자가 없으면 그대로
  ['주의 영광이 성전을 가득 채웠다', '주의 영광이 성전을 가득 채웠다'],
];

let fail = 0;
for (const [input, want] of cases) {
  const got = readNumbers(input);
  if (got !== want) { fail++; console.log(`  [실패] "${input}"\n         나온값: ${got}\n         기대값: ${want}`); }
}

// 수사 자체 검증
const nums = [[0,'영'],[5,'오'],[10,'십'],[15,'십오'],[50,'오십'],[100,'백'],[110,'백십'],[500,'오백'],
              [1000,'천'],[1234,'천이백삼십사'],[10000,'만'],[12000,'만이천'],[123456,'십이만삼천사백오십육'],[100000000,'일억']];
for (const [n, want] of nums) {
  const got = sino(n);
  if (got !== want) { fail++; console.log(`  [실패] sino(${n}) = ${got}, 기대값 ${want}`); }
}
const nats = [[1,'한'],[3,'세'],[4,'네'],[12,'열두'],[20,'스무'],[21,'스물한'],[99,'아흔아홉'],[100,null]];
for (const [n, want] of nats) {
  const got = native(n, true);
  if (got !== want) { fail++; console.log(`  [실패] native(${n}) = ${got}, 기대값 ${want}`); }
}

console.log(fail ? `\n실패 ${fail}건` : `통과 — ${cases.length + nums.length + nats.length}건 모두 정상`);
process.exit(fail ? 1 : 0);
